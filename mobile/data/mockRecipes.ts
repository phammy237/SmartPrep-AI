function heroImage(seed: string): string {
  return placeholderPhotoUri(seed, 800, 600);
}

function ing(id: string, quantity: number, unit?: QuantityUnit, isPantryStaple?: boolean): RecipeIngredient {
  const ingredient = getIngredient(id);
  return {
    ingredientId: id,
    name: ingredient.name,
    imageUri: ingredient.imageUri,
    quantity,
    unit: unit ?? ingredient.defaultUnit,
    isPantryStaple,
  };
}

function reasons(recipeId: string, texts: string[]) {
  return texts.map((text, index) => ({ id: `${recipeId}-r${index + 1}`, text }));
}

